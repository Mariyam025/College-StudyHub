/* =====================================================
   GENERATE 20 REMAINING SUBJECTS × 5 UNITS × 5 QUESTIONS
===================================================== */

remainingSubjects.forEach(subject => {

    const topics = topicMap[subject];

    const bank = questionBank[subject];

    topics.forEach((topic,index) => {

        const questions = [];

        for(let i = 0; i < 5; i++){

            const item = bank[i];

            /*
              Rotate correct answer position so
              answers are not always option A.
            */

            let options = [
                item[1],
                item[2],
                item[3],
                item[4]
            ];

            const correctText = options[0];

            const position = (i + index) % 4;

            const temp = options[position];

            options[position] = correctText;

            options[0] = temp;

            questions.push({

                question:
                    `${item[0]}`,

                options:
                    options,

                answer:
                    position,

                points:
                    10
            });
        }

        quizData.push({

            subject:subject,

            unit:`Unit ${index + 1}`,

            topic:topic,

            questions:questions
        });

    });

});


/* =====================================================
   FIX FIRST 5 SUBJECTS ANSWER POSITIONS
===================================================== */

quizData.forEach((unit,index) => {

    /*
      Make correct answers rotate A/B/C/D
      for all questions.
    */

    unit.questions.forEach((q,qIndex) => {

        /*
          Special questions already have correct
          answers. Rotate their option positions.
        */

        const correctText =
            q.options[q.answer];

        const newPosition =
            (qIndex + index) % 4;

        const temp =
            q.options[newPosition];

        q.options[newPosition] =
            correctText;

        q.options[q.answer] =
            temp;

        q.answer =
            newPosition;

    });

});


